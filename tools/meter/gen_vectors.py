"""Generate firmware/test/test_meter/vectors.h with tinytuya 1.20's own framing and crypto (dummy key, no device).
Run: tools/meter/.venv/bin/python -I tools/meter/gen_vectors.py > firmware/test/test_meter/vectors.h
The C++ Session must build the client frames byte for byte and parse the device frames (test_meter)."""
import hashlib, hmac, struct
from tinytuya.core.message_helper import TuyaMessage, pack_message
from tinytuya.core.crypto_helper import AESCipher

KEY = b"k3y-For-Tests-16"
DEV = "bf00000000000000test1"
T = 1792571700
REMOTE = bytes(range(0xC0, 0xD0))
DEV_IV = bytes(range(0xE0, 0xEC))
DPS = '{"dps":{"1":30503,"6":"CYIAAEUAAMU=","15":196,"16":true}}'


class Gen:
    def __init__(self): self.c = 0x40
    def __call__(self, n):
        b = bytes((self.c + i) & 0xFF for i in range(n)); self.c += n; return b


def mac(k, d): return hmac.new(k, d, hashlib.sha256).digest()
def ecb(k, d, pad=True): return AESCipher(k).encrypt(d, False, pad=pad)
def m55(seq, cmd, payload, k=None): return pack_message(TuyaMessage(seq, cmd, 0, payload, 0, True, 0x55AA, False), hmac_key=k)
def m66(seq, cmd, payload, k, iv, retcode=None):
    return pack_message(TuyaMessage(seq, cmd, retcode, payload, 0, True, 0x6699, iv), hmac_key=k)

out = {}
# ---- 3.3
q = ('{"gwId":"%s","devId":"%s","uid":"%s","t":"%d"}' % (DEV, DEV, DEV, T)).encode()
out["v33_query"] = m55(1, 10, ecb(KEY, q))
body = ('{"devId":"%s",%s,"t":%d}' % (DEV, DPS[1:-1], T)).encode()
out["v33_refresh"] = m55(2, 18, ecb(KEY, b'{"dpId":[6]}'))
out["v33_resp"] = m55(7, 10, struct.pack(">I", 0) + ecb(KEY, body))
out["v33_push"] = m55(8, 8, struct.pack(">I", 0) + b"3.3" + b"\0" * 12 + ecb(KEY, body))
# ---- 3.4
g = Gen(); nonce = g(16)
out["v34_start"] = m55(1, 3, ecb(KEY, nonce), KEY)
out["v34_sessresp"] = m55(1, 4, struct.pack(">I", 0) + ecb(KEY, REMOTE + mac(KEY, nonce)), KEY)
out["v34_finish"] = m55(2, 5, ecb(KEY, mac(KEY, REMOTE)), KEY)
sk = ecb(KEY, bytes(a ^ b for a, b in zip(nonce, REMOTE)), pad=False)
out["v34_query"] = m55(3, 16, ecb(sk, b"{}"), sk)
out["v34_refresh"] = m55(4, 18, ecb(sk, b'{"dpId":[6]}'), sk)
body = ('{"protocol":4,"t":%d,"data":%s}' % (T, DPS)).encode()
out["v34_resp"] = m55(2, 16, struct.pack(">I", 0) + ecb(sk, b"3.4" + b"\0" * 12 + body), sk)
out["v34_sk"] = sk
# ---- 3.5
g = Gen(); nonce = g(16)
out["v35_start"] = m66(1, 3, nonce, KEY, g(12))
out["v35_sessresp"] = m66(1, 4, REMOTE + mac(KEY, nonce), KEY, DEV_IV, retcode=0)
out["v35_finish"] = m66(2, 5, mac(KEY, REMOTE), KEY, g(12))
sk = AESCipher(KEY).encrypt(bytes(a ^ b for a, b in zip(nonce, REMOTE)), False, pad=False, iv=nonce[:12])[12:28]
out["v35_query"] = m66(3, 16, b"{}", sk, g(12))
out["v35_refresh"] = m66(4, 18, b'{"dpId":[6]}', sk, g(12))
out["v35_resp"] = m66(2, 16, b"3.5" + b"\0" * 12 + body.replace(b'"protocol":4', b'"protocol":5'), sk, DEV_IV, retcode=0)
out["v35_sk"] = sk

print("// Generated by tools/meter/gen_vectors.py from tinytuya 1.20 (dummy key, no device). Do not edit.")
print("#pragma once\n#include <stdint.h>\n#include <stddef.h>")
print('static const char* V_KEY = "%s";\nstatic const char* V_DEV = "%s";\nstatic const uint32_t V_T = %d;' % (KEY.decode(), DEV, T))
print('static const char* V_DPS = %s;' % ('"' + DPS.replace('"', '\\"') + '"'))
for k, v in out.items():
    print("static const uint8_t %s[] = {%s};" % (k.upper(), ",".join("0x%02x" % b for b in v)))
