// UI language: English (default) and Bangla. One module-level current language, set by the App
// (setCurrentLang) on every render, so plain functions (format.ts, time.ts, decode.ts, data/alerts.ts)
// read it without a hook; components re-render on a switch because the app context changes.
// Dictionaries: `en` is the source of the keys, `bn` must have every key (type error otherwise).
// Bangla mode also shows Bangla digits through localizeDigits(); charts, CSV, inputs and anything
// written to Firebase keep ASCII digits.
import type { ComponentChildren } from 'preact';
import type { MetricGroup, MetricId } from '../alertMetrics';

export type Lang = 'en' | 'bn';
export const LANG_KEY = 'lang';
export const isLang = (v: unknown): v is Lang => v === 'en' || v === 'bn';

function readStored(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return isLang(v) ? v : 'en';
  } catch {
    return 'en';
  }
}

let current: Lang = readStored();
if (typeof document !== 'undefined') document.documentElement.lang = current;

export const getLang = (): Lang => current;
export const isBn = (): boolean => current === 'bn';

/** Called by the App while rendering (before any child reads a string). */
export function setCurrentLang(l: Lang): void {
  current = l;
}

/** Runs `fn` with English strings and digits (e-mail preview: the mailer writes English). */
export function inEnglish<T>(fn: () => T): T {
  const prev = current;
  current = 'en';
  try {
    return fn();
  } finally {
    current = prev;
  }
}

const BN_DIGITS = '০১২৩৪৫৬৭৮৯';

/** '12:05' -> '১২:০৫' in Bangla mode; unchanged in English. Only ASCII digits are touched. */
export function localizeDigits(s: string): string {
  if (current !== 'bn') return s;
  return s.replace(/[0-9]/g, (d) => BN_DIGITS[d.charCodeAt(0) - 48]);
}

