const fmtVar = (v: string | number) => (typeof v === 'number' ? localizeDigits(String(v)) : v);

/**
 * Translated string for `key`. `{name}` placeholders are filled from `vars`; number values get
 * Bangla digits in Bangla mode, strings are inserted as they are (codes, names, pre-formatted values).
 */
export function t(key: Key, vars?: Vars): string {
  const s: string = (current === 'bn' ? bn[key] : en[key]) ?? en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? fmtVar(vars[name]) : m));
}

/** Like t(), but placeholders may be elements (links, <code>, <strong>); returns children for JSX. */
export function tj(key: Key, vars: Record<string, ComponentChildren>): ComponentChildren[] {
  const s: string = (current === 'bn' ? bn[key] : en[key]) ?? en[key] ?? key;
  const out: ComponentChildren[] = [];
  const re = /\{(\w+)\}/g;
  let last = 0;
  for (let m = re.exec(s); m; m = re.exec(s)) {
    if (m.index > last) out.push(s.slice(last, m.index));
    const v = m[1] in vars ? vars[m[1]] : m[0];
    out.push(typeof v === 'number' ? localizeDigits(String(v)) : v);
    last = m.index + m[0].length;
  }
  if (last < s.length) out.push(s.slice(last));
  return out;
}

